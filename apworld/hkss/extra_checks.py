"""Extra check types (levers, breakable walls, grass) for Hollow Knight x Silksong.

Data lives in apworld/hkss/extra_checks_data.json (generated by tools/export_extra_checks.py).
Locations occupy dedicated sub-ranges inside the Hollow Knight (84,150,000+) and Silksong
(84,250,000+) ID blocks so upstream resyncs never collide with them.
"""

from __future__ import annotations

import json
import pkgutil
from functools import lru_cache
from typing import TYPE_CHECKING, Any

from BaseClasses import Location
from rule_builder.rules import CanReachRegion, Or

from .ids import GAME_NAME, hk_name, ss_name

if TYPE_CHECKING:
    from . import HKSSWorld


KINDS = ("levers", "breakable_walls", "grass")

HK_OPTION_BY_KIND = {
    "levers": "RandomizeLevers",
    "breakable_walls": "RandomizeBreakableWalls",
    "grass": "RandomizeGrass",
}

SS_OPTION_BY_KIND = {
    "levers": "lever_randomization",
    "breakable_walls": "breakable_wall_randomization",
    "grass": "grass_randomization",
}

GROUP_LABELS = {
    "levers": "Levers",
    "breakable_walls": "Breakable Walls",
    "grass": "Grass",
}


class HKExtraLocation(Location):
    game: str = GAME_NAME


class SSExtraLocation(Location):
    game: str = GAME_NAME


@lru_cache(maxsize=1)
def load_extra_checks_data() -> dict[str, Any]:
    raw = pkgutil.get_data(__name__.rpartition(".")[0], "extra_checks_data.json")
    if raw is None:
        raise FileNotFoundError("extra_checks_data.json is missing from the world package")
    return json.loads(raw.decode("utf-8"))


@lru_cache(maxsize=1)
def hk_entries_by_kind() -> dict[str, tuple[dict[str, Any], ...]]:
    data = load_extra_checks_data()["hollow_knight"]
    return {kind: tuple(data.get(kind, ())) for kind in KINDS}


@lru_cache(maxsize=1)
def ss_entries_by_kind() -> dict[str, tuple[dict[str, Any], ...]]:
    data = load_extra_checks_data()["silksong"]
    return {kind: tuple(data.get(kind, ())) for kind in KINDS}


@lru_cache(maxsize=1)
def hk_scene_by_name() -> dict[str, str]:
    table: dict[str, str] = {}
    for entries in hk_entries_by_kind().values():
        for entry in entries:
            table[entry["name"]] = entry["scene"]
    return table


@lru_cache(maxsize=1)
def ss_entry_by_name() -> dict[str, dict[str, Any]]:
    table: dict[str, dict[str, Any]] = {}
    for entries in ss_entries_by_kind().values():
        for entry in entries:
            table[entry["name"]] = entry
    return table


def hk_extra_scene(raw_name: str) -> str | None:
    return hk_scene_by_name().get(raw_name)


def build_extra_location_name_to_id() -> dict[str, int]:
    table: dict[str, int] = {}
    for entries in hk_entries_by_kind().values():
        for entry in entries:
            table[hk_name(entry["name"])] = int(entry["id"])
    for entries in ss_entries_by_kind().values():
        for entry in entries:
            table[ss_name(entry["name"])] = int(entry["id"])
    return table


def build_extra_location_groups() -> dict[str, set[str]]:
    groups: dict[str, set[str]] = {}
    for kind, label in GROUP_LABELS.items():
        hk_set = {hk_name(e["name"]) for e in hk_entries_by_kind()[kind]}
        ss_set = {ss_name(e["name"]) for e in ss_entries_by_kind()[kind]}
        if hk_set:
            groups[f"HK {label}"] = hk_set
            groups.setdefault(label, set()).update(hk_set)
        if ss_set:
            groups[f"SS {label}"] = ss_set
            groups.setdefault(label, set()).update(ss_set)
    return groups


def _hk_white_palace_allows(world: "HKSSWorld", wp_tag: str) -> bool:
    if wp_tag == "none":
        return True
    from .hk.Options import WhitePalace

    wp = world.options.WhitePalace.value
    if wp_tag == "pop":
        return wp == WhitePalace.option_include
    # wp_tag == "palace"
    return wp in (WhitePalace.option_nopathofpain, WhitePalace.option_include)


def active_hk_entries(world: "HKSSWorld") -> list[dict[str, Any]]:
    if not world.has_hk:
        return []
    result: list[dict[str, Any]] = []
    for kind, opt_name in HK_OPTION_BY_KIND.items():
        if not bool(getattr(world.options, opt_name).value):
            continue
        for entry in hk_entries_by_kind()[kind]:
            if _hk_white_palace_allows(world, entry.get("whitePalace", "none")):
                result.append(entry)
    return result


def active_ss_entries(world: "HKSSWorld") -> list[dict[str, Any]]:
    if not world.has_silksong:
        return []
    goal_key = world.get_goal_key()
    no_silk_soar_in_act2 = (
        goal_key in ("act_2", "cursed_ending")
        and (
            world.get_category_mode("Skill") != "anywhere"
            or bool(world.options.silk_soar_begone)
        )
    )
    result: list[dict[str, Any]] = []
    for kind, opt_name in SS_OPTION_BY_KIND.items():
        if not bool(getattr(world.options, opt_name).value):
            continue
        for entry in ss_entries_by_kind()[kind]:
            if goal_key == "act_1" and not entry.get("act1Scope", False):
                continue
            if goal_key in ("act_2", "cursed_ending") and entry.get("act3Only", False):
                continue
            if no_silk_soar_in_act2 and entry.get("requiresSilkSoar", False):
                continue
            result.append(entry)
    return result


def create_extra_regions_and_locations(world: "HKSSWorld") -> tuple[list[dict[str, Any]], list[tuple[dict[str, Any], list[str]]]]:
    """Create enabled HK and Silksong extra check locations.

    Returns ``(created_hk_entries, created_ss_entries_with_nodes)``.
    """
    player = world.player
    menu_region = world.multiworld.get_region("Menu", player)

    created_hk: list[dict[str, Any]] = []
    for entry in active_hk_entries(world):
        loc = HKExtraLocation(player, hk_name(entry["name"]), int(entry["id"]), menu_region)
        menu_region.locations.append(loc)
        created_hk.append(entry)

    created_ss: list[tuple[dict[str, Any], list[str]]] = []
    existing_regions = {
        r.name: r
        for r in world.multiworld.regions
        if r.player == player
    }
    for entry in active_ss_entries(world):
        nodes = [n for n in entry.get("nodes", ()) if n in existing_regions]
        if not nodes:
            continue
        parent = existing_regions[nodes[0]] if len(nodes) == 1 else menu_region
        loc = SSExtraLocation(player, ss_name(entry["name"]), int(entry["id"]), parent)
        parent.locations.append(loc)
        created_ss.append((entry, nodes))

    return created_hk, created_ss


def create_extra_filler_items(
    world: "HKSSWorld",
    hk_count: int,
    ss_count: int,
) -> None:
    """Add one matching filler item per created extra check to keep the item pool balanced."""
    from .silksong import SilksongWorld

    for _ in range(hk_count):
        world.multiworld.itempool.append(world.hk.create_item(world.hk.get_filler_item_name()))
    for _ in range(ss_count):
        world.multiworld.itempool.append(SilksongWorld.create_filler(world))


def set_extra_rules(
    world: "HKSSWorld",
    created_hk: list[dict[str, Any]],
    created_ss: list[tuple[dict[str, Any], list[str]]],
) -> None:
    """Apply Archipelago access rules to all created extra check locations."""
    player = world.player

    for entry in created_hk:
        loc = world.multiworld.get_location(hk_name(entry["name"]), player)
        transitions = tuple(entry["transitions"])
        requires_quake = bool(entry.get("requiresQuake", False))

        def _hk_rule(state, _t=transitions, _q=requires_quake, _p=player) -> bool:
            if not any(state.count(node, _p) for node in _t):
                return False
            if _q and not state.count("QUAKE", _p):
                return False
            if not (
                state.count("LEFTSLASH", _p)
                or state.count("RIGHTSLASH", _p)
                or state.count("UPSLASH", _p)
                or state.count("DOWNSLASH", _p)
            ):
                return False
            return True

        loc.access_rule = _hk_rule

    for entry, nodes in created_ss:
        if len(nodes) > 1:
            loc = world.multiworld.get_location(ss_name(entry["name"]), player)
            world.set_rule(loc, Or(*(CanReachRegion(n) for n in nodes)))


def export_ss_extra_requirements(
    created_ss: list[tuple[dict[str, Any], list[str]]],
) -> dict[str, Any]:
    """Build Silksong map_logic requirement entries for active SS extra checks."""
    reqs: dict[str, Any] = {}
    for entry, nodes in created_ss:
        reqs[entry["name"]] = {
            "alternatives": [{"all_of": [node]} for node in nodes],
        }
    return reqs
